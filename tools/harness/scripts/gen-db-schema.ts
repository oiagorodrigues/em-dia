import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const migrationsDir = join(root, "apps/api/src/db/migrations");
const outFile = join(root, "docs/generated/db-schema.md");

if (!existsSync(migrationsDir)) {
  console.log(`gen-db-schema: ${migrationsDir} does not exist yet, nothing to do`);
  process.exit(0);
}

const sources = readdirSync(migrationsDir)
  .filter((f) => /\.(ts|sql)$/.test(f))
  .sort();

/** Pull SQL out of template literals and quoted strings in .ts files; take .sql files whole. */
function sqlOf(file: string): string {
  const text = readFileSync(join(migrationsDir, file), "utf8");
  if (file.endsWith(".sql")) return text;
  const chunks = [...text.matchAll(/`([^`]*)`/g)].map((m) => m[1]!);
  return chunks.filter((c) => /\b(create|alter|drop)\b/i.test(c)).join("\n");
}

const tables = new Map<string, string[]>();
const indexes: string[] = [];

for (const file of sources) {
  const sql = sqlOf(file);
  for (const m of sql.matchAll(
    /create\s+table\s+(?:if\s+not\s+exists\s+)?["`]?(\w+)["`]?\s*\(([\s\S]*?)\)\s*(?:strict|without\s+rowid)?[\s,]*;/gi,
  )) {
    const cols = m[2]!
      .split(/,\s*(?![^(]*\))/)
      .map((c) => c.trim().replace(/\s+/g, " "))
      .filter(Boolean);
    tables.set(m[1]!, cols);
  }
  for (const m of sql.matchAll(/alter\s+table\s+["`]?(\w+)["`]?\s+add\s+column\s+([^;]+);/gi)) {
    tables.get(m[1]!)?.push(m[2]!.trim().replace(/\s+/g, " "));
  }
  for (const m of sql.matchAll(
    /alter\s+table\s+["`]?(\w+)["`]?\s+drop\s+column\s+["`]?(\w+)["`]?\s*;/gi,
  )) {
    const cols = tables.get(m[1]!);
    if (cols) {
      tables.set(
        m[1]!,
        cols.filter((c) => c.split(" ")[0] !== m[2]),
      );
    }
  }
  for (const m of sql.matchAll(/create\s+(?:unique\s+)?index\s+[^;]+;/gi)) {
    indexes.push(m[0].trim().replace(/\s+/g, " "));
  }
}

const lines = [
  "# Database schema (generated)",
  "",
  "Generated by `bun run docs:schema` from `apps/api/src/db/migrations`. Do not edit by hand.",
  "",
];
for (const [name, cols] of [...tables].sort(([a], [b]) => a.localeCompare(b))) {
  lines.push(`## ${name}`, "", "```sql", ...cols.map((c) => `  ${c}`), "```", "");
}
if (indexes.length) lines.push("## Indexes", "", "```sql", ...indexes, "```", "");

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, lines.join("\n"));
console.log(`gen-db-schema: wrote ${tables.size} tables to ${outFile}`);
